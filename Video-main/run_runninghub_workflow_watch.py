import asyncio
import os
from pathlib import Path
from typing import Any, Dict, List, Optional
from urllib.parse import urlparse

import aiohttp

from comfykit.comfyui.runninghub_client import RunningHubClient


def _infer_ext(file_type: str, file_url: str) -> str:
    ft = (file_type or "").lower()
    if "mp4" in ft:
        return ".mp4"
    if "webm" in ft:
        return ".webm"
    if "mov" in ft:
        return ".mov"
    if "avi" in ft:
        return ".avi"

    # Fallback: infer from URL path
    path = urlparse(file_url).path
    if "." in path:
        return "." + path.split(".")[-1].split("?")[0]
    return ".bin"

def _to_ui_video_filename(uploaded_file_name: str) -> str:
    """
    RunningHub upload API returns fileName like 'api/<hash>.mp4'.
    In RunningHub UI, VHS_LoadVideoFFmpeg expects a plain '<hash>.mp4'.
    """
    v = (uploaded_file_name or "").strip()
    if v.startswith("api/"):
        return v.split("/", 1)[1]
    return v


async def _download_to_path(session: aiohttp.ClientSession, url: str, dest_path: Path) -> None:
    dest_path.parent.mkdir(parents=True, exist_ok=True)

    async with session.get(url) as resp:
        resp.raise_for_status()
        with open(dest_path, "wb") as f:
            async for chunk in resp.content.iter_chunked(1024 * 256):
                if not chunk:
                    continue
                f.write(chunk)


async def main() -> None:
    api_key = os.getenv("RUNNINGHUB_API_KEY") or ""
    if not api_key:
        raise RuntimeError("RUNNINGHUB_API_KEY is not set in environment.")

    # Your requested workflow
    workflow_id = "2037049003786903554"
    # Fixed seed (as configured in your RunningHub UI)
    flashvsr_seed = 692322036734462

    # Source video on your local disk
    # Test with a known-good H264/yuv420p video generated by RunningHub
    input_video_path = Path(r"C:\Users\Administrator\Desktop\成品\测试加高.mp4")
    if not input_video_path.exists():
        raise FileNotFoundError(str(input_video_path))

    output_dir = Path(r"C:\Users\Administrator\Desktop\1.27")
    output_dir.mkdir(parents=True, exist_ok=True)

    # RunningHub API base URL
    base_url = "https://www.runninghub.cn"

    # Client
    client = RunningHubClient(api_key=api_key, base_url=base_url, retry_count=3, instance_type=None)

    try:
        print(f"Uploading: {input_video_path}", flush=True)
        uploaded_file_name = await client.upload_file(str(input_video_path))
        print(f"Uploaded. fileName/url: {uploaded_file_name}", flush=True)

        # Align with UI behavior: VHS_LoadVideoFFmpeg wants a plain mp4 filename
        ui_video_value = _to_ui_video_filename(uploaded_file_name)
        print(f"Using UI-style video value: {ui_video_value}", flush=True)

        async def _create_task_with_video_value(video_value: str) -> Dict[str, Any]:
            # From fetched workflow JSON:
            # nodeId=21 (VHS_LoadVideoFFmpeg) has input field `video`
            # nodeId=19 (FlashVSRNode) has input field `seed` (must be fixed)
            node_info_list: List[Dict[str, Any]] = [
                {"nodeId": "21", "fieldName": "video", "fieldValue": video_value},
                {"nodeId": "19", "fieldName": "seed", "fieldValue": flashvsr_seed},
            ]
            return await client.create_task(workflow_id, node_info_list=node_info_list)

        print(f"Creating RunningHub task (workflowId={workflow_id}) ...", flush=True)

        async def _create_with_retry(video_value: str) -> Dict[str, Any]:
            # Handle TASK_QUEUE_MAXED by backoff retry.
            backoff_s = 2
            while True:
                try:
                    return await _create_task_with_video_value(video_value)
                except Exception as e:
                    msg = str(e)
                    if "TASK_QUEUE_MAXED" in msg:
                        print(f"Queue maxed, retrying create in {backoff_s}s ...", flush=True)
                        await asyncio.sleep(backoff_s)
                        backoff_s = min(backoff_s * 2, 30)
                        continue
                    raise

        try:
            task_data = await _create_with_retry(ui_video_value)
        except Exception as e:
            # Some RunningHub environments validate the video path strictly and may require 'api/<hash>.mp4'
            msg = str(e)
            if "Invalid video file" in msg or "custom_validation_failed" in msg:
                print("UI-style video value rejected by validator; retrying with api/<hash>.mp4 ...", flush=True)
                task_data = await _create_with_retry(uploaded_file_name)
            else:
                raise
        task_id = task_data.get("taskId") or task_data.get("task_id")
        if not task_id:
            raise RuntimeError(f"Failed to create task. Response: {task_data}")
        print(f"Task created: {task_id}", flush=True)

        print("Polling task status (QUEUED/RUNNING/FAILED/SUCCESS) ...", flush=True)
        while True:
            status_info = await client.query_task_status(task_id)
            status = status_info.get("status")
            msg = status_info.get("msg", "")
            code = status_info.get("code", "")
            print(f"[{task_id}] status={status} code={code} msg={msg}", flush=True)

            if status == "SUCCESS":
                break
            if status == "FAILED":
                raise RuntimeError(f"RunningHub task failed: {msg}")

            await asyncio.sleep(2)

        print("Task SUCCESS. Fetching outputs ...", flush=True)
        result_data = await client.query_task_result(task_id)

        # Collect all video outputs
        videos: List[Dict[str, Any]] = []
        for item in result_data or []:
            if not isinstance(item, dict):
                continue
            file_type = (item.get("fileType") or "").lower()
            if "video" in file_type or "mp4" in file_type or file_type.startswith("mp4") or item.get("fileUrl"):
                # Keep all potential media; we'll filter when downloading by fileType/URL
                if "mp4" in file_type or "video" in file_type or item.get("fileUrl"):
                    videos.append(item)

        if not videos:
            print("No video outputs found in result.")
            print(f"Raw result_data: {result_data}")
            return

        timeout = aiohttp.ClientTimeout(total=0)  # no overall timeout for downloads
        async with aiohttp.ClientSession(timeout=timeout) as download_session:
            downloaded = 0
            for idx, item in enumerate(videos):
                file_url = item.get("fileUrl")
                file_type = item.get("fileType", "")
                if not file_url:
                    continue

                # Only download mp4-like outputs (most likely “成片”)
                ext = _infer_ext(file_type, file_url)
                # Skip non-video extensions if server returns images/text too
                if ext not in [".mp4", ".mov", ".avi", ".webm"]:
                    continue

                dest = output_dir / f"runninghub_{task_id}_{idx}{ext}"
                print(f"Downloading output {idx}: {file_type} -> {dest.name}", flush=True)
                await _download_to_path(download_session, file_url, dest)
                downloaded += 1

        print(f"Download complete. videos downloaded: {downloaded}", flush=True)
        print(f"Saved to: {output_dir}", flush=True)

    finally:
        # Best effort close
        try:
            await client.close()
        except Exception:
            pass


if __name__ == "__main__":
    asyncio.run(main())

